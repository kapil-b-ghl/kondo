// Builds src/tokens/primitives.css from tokens/primitives.json.
// Every CSS variable name mirrors the Figma variable path, so a token in code
// can always be traced back to Figma: color/primary/blue/600 → --hr-color-primary-blue-600
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const p = JSON.parse(readFileSync(new URL('../tokens/primitives.json', import.meta.url)));
const slug = (s) => s.replace(/\[(\d+)\]/g, '_$1').replace(/\//g, '-');
const lines = [];
const add = (name, value) => lines.push(`  --hr-${slug(name)}: ${value};`);

lines.push('  /* colour */');
add('color/neutral/white/base', p.white);
add('color/neutral/black/base', p.black);
for (const [scale, values] of Object.entries(p.color)) {
  values.forEach((hex, i) => add(`color/${scale}/${p.colorSteps[i]}`, hex));
}
const groups = [['spacing', 'spacing', 'px'], ['radius', 'border/radius', 'px'], ['borderWidth', 'border/width', 'px'],
  ['fontSize', 'font/size', 'px'], ['lineHeight', 'font/line-height', 'px'], ['fontWeight', 'font/weight', ''], ['zIndex', 'z-index', '']];
for (const [key, prefix, unit] of groups) {
  lines.push(`  /* ${prefix} */`);
  for (const [k, v] of Object.entries(p[key])) add(`${prefix}/${k}`, v === 0 ? '0' : `${v}${unit}`);
}
lines.push('  /* shadow */');
for (const [k, v] of Object.entries(p.shadow)) add(`shadow/${k}`, v);
lines.push('  --hr-font-family: "Inter", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;');

mkdirSync(new URL('../src/tokens/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/tokens/primitives.css', import.meta.url),
  `/* GENERATED by scripts/build-tokens.mjs from tokens/primitives.json. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`);
console.log(`primitives.css: ${lines.filter((l) => l.includes('--hr-')).length} tokens`);
