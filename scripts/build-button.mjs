// Generates the HrButton stylesheet and audit from specs/button.figma.json.
//
// Policy ("exactly to spec, with a paper trail"):
//  * Code reproduces every Figma variant value.
//  * The script compares the five themes of each Variant×State and lists every
//    theme that breaks the pattern the others share.
//  * Colour differences are kept exactly as Figma has them (the brand blue may
//    be deliberately different) and go to the audit for a designer to decide.
//  * Only a lone shadow / focus-ring deviation is auto-corrected (for example a
//    focus ring baked into a resting state), because shipping it would look broken.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const spec = JSON.parse(readFileSync(new URL('../specs/button.figma.json', import.meta.url)));
const SCALE = { blue: 'primary-blue', gray: 'neutral-gray', error: 'secondary-error', warning: 'secondary-warning', success: 'secondary-success', white: 'neutral-white' };
const THEME_SCALE = { Primary: 'blue', Neutral: 'gray', Destructive: 'error', Warning: 'warning', Success: 'success' };
const { Variant: variants, Theme: themes, State: states } = spec.axes;

const parse = (s) => {
  const [bg, bd, fg, ...fx] = s.split(' ');
  return { bg, bd, fg, fx: fx.join(' ') };
};
// Theme-independent "shape" of a value: blue/600 → $/600, white/base stays literal.
const shape = (v, theme) => v.replace(THEME_SCALE[theme] + '/', '$/').replace(/(primary|gray|error|warning|success)-100/, '$-100');
const cssColor = (v) => {
  if (v === '-') return 'transparent';
  const [scale, step] = v.split('/');
  return `var(--hr-color-${SCALE[scale]}-${step})`;
};
const ringScale = { primary: 'primary-blue', gray: 'neutral-gray', error: 'secondary-error', warning: 'secondary-warning', success: 'secondary-success' };
const cssEffect = (fx) => {
  if (!fx || fx === '-') return 'none';
  const parts = [];
  if (fx.startsWith('xs')) parts.push('var(--hr-shadow-xs)');
  const ring = fx.match(/4px (\w+)-100/);
  if (ring) parts.push(`0 0 0 4px var(--hr-color-${ringScale[ring[1]]}-100)`);
  return parts.join(', ') || 'none';
};

const gaps = [];
const resolved = {};
for (const v of variants) for (const st of states) {
  for (const slot of ['bg', 'bd', 'fg', 'fx']) {
    const byTheme = Object.fromEntries(themes.map((t) => [t, parse(spec.colors[`${v}.${t}.${st}`])[slot]]));
    const counts = {};
    for (const t of themes) { const s = shape(byTheme[t], t); counts[s] = (counts[s] || 0) + 1; }
    const [majority, n] = Object.entries(counts).sort((a, b) => b[1] - a[1])[0];
    for (const t of themes) {
      const key = `${v}.${t}.${st}`;
      resolved[key] ??= parse(spec.colors[key]);
      const s = shape(byTheme[t], t);
      if (s === majority) continue;
      const fixable = slot === 'fx' && n === themes.length - 1;
      const expected = majority.replace('$/', THEME_SCALE[t] + '/').replace('$-100', (THEME_SCALE[t] === 'blue' ? 'primary' : THEME_SCALE[t]) + '-100');
      if (fixable) resolved[key][slot] = expected;
      gaps.push({
        variant: `${v} / ${t} / ${st}`,
        property: { bg: 'background', bd: 'border', fg: 'text colour', fx: 'shadow / focus ring' }[slot],
        figma: byTheme[t], othersUse: majority.replace('$', THEME_SCALE[t]),
        codeUses: fixable ? 'the value the other four themes use' : 'Figma value, unchanged',
        severity: fixable ? 'likely-figma-error' : 'needs-design-decision',
      });
    }
  }
}

// Plain-language summary per gap, grouped so the list reads like a design review.
const describe = (g) => `${g.variant}: ${g.property} is ${g.figma} in Figma, but the other themes use ${g.othersUse}. Code uses ${g.codeUses}.`;

let css = `/* GENERATED by scripts/build-button.mjs from specs/button.figma.json. Do not edit by hand. */\n`;
for (const v of variants) for (const t of themes) {
  const sel = `.hr-btn--${v.toLowerCase()}.hr-btn--${t.toLowerCase()}`;
  const decl = (st) => {
    const r = resolved[`${v}.${t}.${st}`];
    const p = st === 'Default' ? '' : '-' + st.toLowerCase();
    return `--_bg${p}:${cssColor(r.bg)};--_bd${p}:${cssColor(r.bd)};--_fg${p}:${cssColor(r.fg)};--_fx${p}:${cssEffect(r.fx)};`;
  };
  css += `${sel}{${states.map(decl).join('')}}\n`;
}
for (const [size, s] of Object.entries(spec.sizes)) {
  const [px, py] = s.pad.split('x');
  const [fs, lh] = s.font.split('/');
  css += `.hr-btn--${size}{--_h:${s.h}px;--_px:${px}px;--_py:${py}px;--_r:${s.r}px;--_gap:${s.gap}px;--_fs:${fs}px;--_lh:${lh}px;--_icon:${s.icon}px;}\n`;
}
for (const [size, f] of Object.entries(spec.linkSizes)) {
  const [fs, lh] = f.split('/');
  css += `.hr-btn--link.hr-btn--${size}{--_fs:${fs}px;--_lh:${lh}px;}\n`;
}

const out = (p) => new URL(p, import.meta.url);
mkdirSync(out('../src/components/button/'), { recursive: true });
mkdirSync(out('../registry/'), { recursive: true });
writeFileSync(out('../src/components/button/button.generated.css'), css);

const audit = {
  component: 'Button',
  figmaNode: spec.figma.componentSet,
  figmaUrl: `https://www.figma.com/design/${spec.figma.fileKey}/HighRise-1.1?node-id=${spec.figma.componentSet.replace(':', '-')}`,
  checked: new Date().toISOString().slice(0, 10),
  variantsInFigma: variants.length * themes.length * states.length * Object.keys(spec.sizes).length * 2,
  variantsInCode: 'all (props: variant, theme, size, iconOnly; states via :hover :active :focus-visible :disabled)',
  status: gaps.some((g) => g.severity === 'needs-design-decision') ? 'matches-with-open-questions' : gaps.length ? 'matches-with-fixes' : 'matches',
  gaps: gaps.map((g) => ({ ...g, summary: describe(g) })),
};
writeFileSync(out('../registry/button.audit.json'), JSON.stringify(audit, null, 2) + '\n');
console.log(`button.generated.css written · ${gaps.length} audit gaps (${gaps.filter((g) => g.severity === 'likely-figma-error').length} auto-resolved)`);
